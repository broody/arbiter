// Rebuild sdk/src/poseidon-wasm.mjs, the WebAssembly Poseidon that
// sdk/src/poseidon.mjs loads, from the Rust crate in sdk/poseidon
// (starknet-crypto's PoseidonHasher). Needs Rust with the wasm32-unknown-unknown
// target (`rustup target add wasm32-unknown-unknown`).
// Usage (from the repo root): node sdk/scripts/build-poseidon.mjs
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const crate = fileURLToPath(new URL('../poseidon/', import.meta.url));
execFileSync('cargo', ['build', '--release', '--locked', '--target', 'wasm32-unknown-unknown'], { cwd: crate, stdio: 'inherit' });
const wasm = await readFile(new URL('../poseidon/target/wasm32-unknown-unknown/release/arbiter_poseidon.wasm', import.meta.url));
const sha256 = createHash('sha256').update(wasm).digest('hex');
await writeFile(new URL('../src/poseidon-wasm.mjs', import.meta.url), `// Generated by sdk/scripts/build-poseidon.mjs from sdk/poseidon. Do not edit.
// ${wasm.length} bytes, sha256 ${sha256}
export const POSEIDON_WASM = '${wasm.toString('base64')}';
`);
console.log(`sdk/src/poseidon-wasm.mjs: ${wasm.length} bytes, sha256 ${sha256}`);
