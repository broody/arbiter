// Plays a scripted counter game through the JS SDK and writes the signed
// transcript and expected results as Cairo fixtures for examples/counter.
// Usage (from the repo root): node sdk/scripts/gen-counter-fixtures.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  MOVE_PLAY, MOVE_RECOMMIT, MOVE_REVEAL, applyStep, checkpointHash, contextHash, hex, open,
  publicKey, rngChain, sign, stateHash, tag, verify,
} from '../src/index.mjs';

import { ADD, GAMBLE, counter } from '../examples/counter.mjs';

const RNG_LEN = 8;
const privateKeys = [0x1a2b3cn, 0x4d5e6fn];
const chains = [rngChain(0x5eed0n, RNG_LEN), rngChain(0x5eed1n, RNG_LEN)];
const recommitChain = rngChain(0x5eed2n, RNG_LEN);
const config = { target: 20 };
const terms = {
  chain_id: tag('SN_TEST'), channel: 0xc4a11e1n, game_id: 1n, prover: 0xad0b7e5n,
  response_seconds: 3600,
  players: [0xa11cen, 0xb0bn],
  keys: privateKeys.map(publicKey),
  rng_tips: chains.map(c => c[RNG_LEN]),
  config,
};
const context = contextHash(counter, terms);

let env = open(counter, config, terms.rng_tips);
const signed = [];
function play(step) {
  const { env: next, message } = applyStep(counter, context, config, env, step);
  const signature = sign(message, privateKeys[step.seat]);
  if (!verify(message, signature, terms.keys[step.seat])) throw Error('Signature self-check failed');
  signed.push({ step, signature });
  env = next;
}
const add = (seat, amount) => play({ seat, move: { kind: MOVE_PLAY, action: { kind: ADD, amount } } });

add(0, 3);
play({ seat: 1, move: { kind: MOVE_PLAY, action: { kind: GAMBLE, amount: 0 } }, entropy: chains[1][RNG_LEN - 1] });
play({ seat: 0, move: { kind: MOVE_REVEAL, value: chains[0][RNG_LEN - 1] } });
play({ seat: 0, move: { kind: MOVE_RECOMMIT, tip: recommitChain[RNG_LEN] } });
play({ seat: 0, move: { kind: MOVE_PLAY, action: { kind: GAMBLE, amount: 0 } }, entropy: recommitChain[RNG_LEN - 1] });
play({ seat: 1, move: { kind: MOVE_REVEAL, value: chains[1][RNG_LEN - 2] } });
while (!env.outcome.finished) add(env.game.next, Math.min(3, env.game.target - env.game.total));

const finalHash = stateHash(counter, env);
const checkpoint = checkpointHash(counter, context, 0, finalHash);
const acks = privateKeys.map(k => sign(checkpoint, k));

// ---- emit Cairo ----
const h = hex;
const bool = b => (b ? 'true' : 'false');
const spanOf = xs => `array![${xs.map(h).join(', ')}].span()`;
const sig = s => `Signature { r: ${h(s.r)}, s: ${h(s.s)} }`;
function moveCairo(m) {
  switch (m.kind) {
    case MOVE_PLAY: return `Move::Play(Action { kind: ${m.action.kind}, amount: ${m.action.amount} })`;
    case MOVE_REVEAL: return `Move::Reveal(${h(m.value)})`;
    case MOVE_RECOMMIT: return `Move::Recommit(${h(m.tip)})`;
    default: return 'Move::Resign';
  }
}
const stepCairo = s => `Step { seat: ${s.seat}, action: ${moveCairo(s.move)}, entropy: ${h(s.entropy ?? 0n)} }`;
const g = env.game;

const out = `// Generated by sdk/scripts/gen-counter-fixtures.mjs. Do not edit.
use referee::{Envelope, Move, Outcome, Pending, Signature, SignedStep, Step, Terms};
use crate::{Action, Config, Counter};

pub const CONTEXT: felt252 = ${h(context)};
pub const STATE_HASH: felt252 = ${h(finalHash)};
pub const CHECKPOINT: felt252 = ${h(checkpoint)};
pub const RNG_LEN: u32 = ${RNG_LEN};
pub const SEED_0: felt252 = ${h(chains[0][0])};
pub const SEED_1: felt252 = ${h(chains[1][0])};

pub fn terms() -> Terms<Config> {
    Terms {
        chain_id: ${h(terms.chain_id)},
        channel: ${h(terms.channel)},
        game_id: ${h(terms.game_id)},
        prover: ${h(terms.prover)},
        response_seconds: ${terms.response_seconds},
        players: ${spanOf(terms.players)},
        keys: ${spanOf(terms.keys)},
        rng_tips: ${spanOf(terms.rng_tips)},
        config: Config { target: ${config.target} },
    }
}

pub fn steps() -> Array<SignedStep<Action>> {
    array![
${signed.map(s => `        SignedStep { step: ${stepCairo(s.step)}, signature: ${sig(s.signature)} },`).join('\n')}
    ]
}

pub fn expected() -> Envelope<Counter> {
    Envelope {
        seq: ${env.seq},
        transcript: ${h(env.transcript)},
        support_turn: ${env.support_turn},
        last_seat: ${env.last_seat},
        pending: Pending { active: ${bool(env.pending.active)}, seat: ${env.pending.seat}, seq: ${env.pending.seq}, entropy: ${h(env.pending.entropy)} },
        rng_heads: ${spanOf(env.rng_heads)},
        outcome: Outcome { finished: ${bool(env.outcome.finished)}, winner: ${env.outcome.winner}, reason: ${env.outcome.reason} },
        game: Counter { total: ${g.total}, next: ${g.next}, gamble: ${bool(g.gamble)}, winner: ${g.winner}, target: ${g.target} },
    }
}

pub fn acks() -> Array<Signature> {
    array![${acks.map(sig).join(', ')}]
}
`;

const target = fileURLToPath(new URL('../../examples/counter/src/fixtures.cairo', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}: ${signed.length} steps, total ${g.total}, winner seat ${env.outcome.winner - 1}`);
